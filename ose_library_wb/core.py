"""Headless core for the OSE Library Workbench.

This module intentionally imports no Qt, FreeCAD, or FreeCADGui symbols. GUI
commands pass an existing document object into compile and validation helpers.

``validate_live`` returns one standard ``libtools.report.Report`` with
``tier="code+output"``. It runs tier-1 code validation and tier-2 output
validation, prefixes check names with ``code:`` or ``output:``, and writes the
same combined report JSON to ``<library-root>/reports/<entry-id>.json``.
"""

from __future__ import annotations

from copy import deepcopy
from importlib import util
import pprint
import sys
import traceback
from pathlib import Path
from types import ModuleType
from typing import Any

from libtools.code_validator import validate_code
from libtools.compile_entry import extract_shapes
from libtools.output_validator import failure_report, validate_output
from libtools.registry import Entry, discover, load_schema
from libtools.report import Check, Report, write_report


EXPORT_BANNER = (
    "# Generated by OSE Library Workbench v0.\n"
    "# Merge these schema changes into schema.py by hand.\n\n"
)


def open_library(root: Path) -> list[Entry]:
    """Open a Schema Canon library root and return sorted libtools entries."""

    root = Path(root)
    if not root.is_dir():
        raise FileNotFoundError(f"library root does not exist: {root}")
    library = root / "library"
    if not library.is_dir():
        raise ValueError(f"not a library root, missing directory: {library}")
    return sorted(discover(root), key=lambda entry: (entry.layer, entry.id))


def latest_report(root: Path, entry_id: str) -> dict | None:
    """Return the latest report JSON for an entry, if present."""

    import json

    path = Path(root) / "reports" / f"{entry_id}.json"
    if not path.is_file():
        return None
    return json.loads(path.read_text(encoding="utf-8"))


def compile_entry_into(
    entry: Entry, doc: Any, schema_override: dict | None = None
) -> list[Any]:
    """Compile an entry into ``doc`` and return objects created by the compiler."""

    schema = load_schema(entry)
    if schema_override:
        schema = _deep_merge(schema, schema_override)

    before = {id(obj) for obj in getattr(doc, "Objects", [])}
    compiler = _load_compiler(entry.compiler_path)
    result = compiler.compile(schema, doc)

    created = [obj for obj in getattr(doc, "Objects", []) if id(obj) not in before]
    if created:
        return created
    if isinstance(result, list):
        return result
    if result is None:
        return []
    return [result]


def validate_live(entry: Entry, doc: Any) -> Report:
    """Run code and live-output checks, write a combined report, and return it."""

    code_report = validate_code(entry)
    try:
        shapes, common_volume_fn = extract_shapes(doc)
        output_report = validate_output(entry, shapes, common_volume_fn)
    except Exception:
        output_report = failure_report(entry, traceback.format_exc())

    report = Report(
        id=entry.id,
        layer=entry.layer,
        status=entry.status,
        tier="code+output",
        checks=[
            *(_prefix_checks("code", code_report.checks)),
            *(_prefix_checks("output", output_report.checks)),
        ],
    )
    write_report(report, _library_root_for(entry) / "reports")
    return report


def export_schema_new(entry: Entry, edited: dict) -> Path:
    """Write edited schema data to ``schema.py.new`` beside the entry schema."""

    path = entry.schema_path.with_name("schema.py.new")
    body = "SCHEMA = " + pprint.pformat(edited, width=100, sort_dicts=False) + "\n"
    path.write_text(EXPORT_BANNER + body, encoding="utf-8")
    return path


def _deep_merge(base: dict, override: dict) -> dict:
    merged = deepcopy(base)
    for key, value in override.items():
        if isinstance(value, dict) and isinstance(merged.get(key), dict):
            merged[key] = _deep_merge(merged[key], value)
        else:
            merged[key] = deepcopy(value)
    return merged


def _load_compiler(path: Path) -> ModuleType:
    spec = util.spec_from_file_location(f"_ose_library_wb_compiler_{path.parent.name}", path)
    if spec is None or spec.loader is None:
        raise ImportError(f"could not load compiler from {path}")

    module = util.module_from_spec(spec)
    parent = str(path.parent)
    inserted = False
    if parent not in sys.path:
        sys.path.insert(0, parent)
        inserted = True
    try:
        spec.loader.exec_module(module)
    finally:
        if inserted:
            try:
                sys.path.remove(parent)
            except ValueError:
                pass
    return module


def _prefix_checks(prefix: str, checks: list[Check]) -> list[Check]:
    return [Check(f"{prefix}:{check.name}", check.passed, check.detail) for check in checks]


def _library_root_for(entry: Entry) -> Path:
    return entry.path.parents[2]
